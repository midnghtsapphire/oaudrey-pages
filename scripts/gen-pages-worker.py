#!/usr/bin/env python3
"""IndexRunner: pack the built wiki (wiki-site/) into one Cloudflare Pages `_worker.js`.

Used when the Pages asset-upload JWT is not available (direct upload through the
Cloudflare API connector returned 403). The Worker serves exactly the files in
wiki-site/, GET/HEAD only, no cookies, no analytics. Output: wiki-worker/_worker.js
(not committed). Upload it as the only file of a Pages deployment with manifest {}.

A normal `wrangler pages deploy wiki-site --project-name oaudrey-wiki` (or a Pages git
connection) replaces this and needs no script.
"""
import base64, json, mimetypes, os, sys
root = sys.argv[1] if len(sys.argv) > 1 else "wiki-site"
out = sys.argv[2] if len(sys.argv) > 2 else "wiki-worker/_worker.js"
for ext, ct in {".js": "text/javascript", ".json": "application/json", ".svg": "image/svg+xml",
                ".woff2": "font/woff2", ".map": "application/json", ".xml": "application/xml",
                ".webmanifest": "application/manifest+json"}.items():
    mimetypes.add_type(ct, ext)
assets = {}
for d, _, fs in os.walk(root):
    for f in sorted(fs):
        if f.endswith(".gz"):
            continue
        p = os.path.join(d, f)
        rel = "/" + os.path.relpath(p, root).replace(os.sep, "/")
        ct = mimetypes.guess_type(f)[0] or "application/octet-stream"
        if ct.startswith("text/") or ct in ("application/json", "application/xml"):
            ct += "; charset=utf-8"
        assets[rel] = [ct, base64.b64encode(open(p, "rb").read()).decode()]
js = """// Generated by scripts/gen-pages-worker.py. Do not edit.
const A = %s;
const SEC = {"X-Content-Type-Options":"nosniff","Referrer-Policy":"no-referrer","X-Frame-Options":"DENY","Permissions-Policy":"interest-cohort=()"};
function bytes(b64){const s=atob(b64);const u=new Uint8Array(s.length);for(let i=0;i<s.length;i++)u[i]=s.charCodeAt(i);return u;}
function resp(path, status, head){const a=A[path];const h=new Headers(SEC);h.set("Content-Type",a[0]);h.set("Cache-Control",path.startsWith("/assets/")?"public, max-age=86400":"public, max-age=300");return new Response(head?null:bytes(a[1]),{status,headers:h});}
export default {
  async fetch(req){
    if(req.method!=="GET"&&req.method!=="HEAD")return new Response("Method not allowed",{status:405,headers:{Allow:"GET, HEAD"}});
    const u=new URL(req.url);let p=decodeURIComponent(u.pathname);
    const head=req.method==="HEAD";
    if(A[p])return resp(p,200,head);
    if(p.endsWith("/")&&A[p+"index.html"])return resp(p+"index.html",200,head);
    if(!p.endsWith("/")&&A[p+"/index.html"]){u.pathname=p+"/";return Response.redirect(u.toString(),301);}
    return resp("/404.html",404,head);
  }
};
""" % json.dumps(assets, separators=(",", ":"))
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write(js)
print(f"{len(assets)} files, {len(js)} bytes -> {out}")
